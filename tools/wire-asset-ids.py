Fetcher = Callable[[str], "tuple[int | None, bytes | None, str | None]"]


def _urllib_fetch(url: str) -> tuple[int | None, bytes | None, str | None]:
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT, "Accept": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=20) as r:
            return r.status, r.read(), None
    except urllib.error.HTTPError as e:
        return e.code, None, f"HTTP {e.code}"
    except Exception as e:  # noqa: BLE001 - reported, never turned into "not owned"
        return None, None, repr(e)


class Net:
    def __init__(self, cache: Path, fetch: Fetcher | None = None, now: Callable[[], dt.datetime] | None = None,
                 sleep: Callable[[float], None] = time.sleep) -> None:
        self.cache, self.fetch, self.now, self.sleep = cache, fetch or _urllib_fetch, now or _utcnow, sleep
        self._last = 0.0
        self.requests = 0

    def get(self, url: str, name: str, max_age: float | None) -> dict:
        """max_age None = any cached copy; 0 = always fetch."""
        path = self.cache / f"{name}.json"
        if path.is_file() and max_age != 0:
            rec = json.loads(path.read_text(encoding="utf-8"))
            age = (self.now() - _parse_utc(rec["fetched"])).total_seconds()
            if max_age is None or age <= max_age:
                rec["cached"] = True
                return rec
        wait = REQUEST_GAP - (time.monotonic() - self._last)
        if wait > 0:
            self.sleep(wait)
        status, body, err = self.fetch(url)
        self._last = time.monotonic()
        self.requests += 1
        rec: dict = {"url": url, "status": status, "fetched": _iso(self.now()), "error": err}
        if body is not None:
            try:
                rec["data"] = json.loads(body.decode("utf-8"))
            except ValueError:
                rec["error"] = "response is not JSON"
        self.cache.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(rec, indent=1, sort_keys=True), encoding="utf-8")
        rec["cached"] = False
        return rec

    def owned(self, asset_id: int, max_age: float | None) -> tuple[bool | None, str]:
        rec = self.get(f"https://inventory.roblox.com/v1/users/{OWNER_USER_ID}/items/Asset/{asset_id}", f"inv_{asset_id}", max_age)
        if rec.get("status") != 200 or not isinstance(rec.get("data"), dict):
            return None, f"inventory API error ({rec.get('error') or rec.get('status')}) at {rec['fetched']}"
        return bool(rec["data"].get("data")), f"inventory API {rec['fetched']}{' (cached)' if rec.get('cached') else ''}"

    def store(self, asset_id: int, max_age: float | None) -> tuple[dict | None, str]:
        rec = self.get(f"https://economy.roblox.com/v2/assets/{asset_id}/details", f"details_{asset_id}", max_age)
        if rec.get("status") != 200 or not isinstance(rec.get("data"), dict):
            return None, f"economy API error ({rec.get('error') or rec.get('status')}) at {rec['fetched']}"
        return rec["data"], f"economy API {rec['fetched']}"


def _utcnow() -> dt.datetime:
    return dt.datetime.now(dt.timezone.utc).replace(microsecond=0)


def _iso(t: dt.datetime) -> str:
    return t.astimezone(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _parse_utc(s: str) -> dt.datetime:
    return dt.datetime.strptime(s, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=dt.timezone.utc)


