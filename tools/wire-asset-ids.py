_LONG_OPEN = re.compile(r"\[(=*)\[")
_IDENT_EQ = re.compile(r"([A-Za-z_][A-Za-z0-9_]*)\s*=(?!=)\s*")


def _skip(text: str, i: int) -> int | None:
    """Index just after the string or comment that starts at i, else None."""
    c = text[i]
    if c == "-" and text.startswith("--", i):
        m = _LONG_OPEN.match(text, i + 2)
        if m:
            end = text.find("]" + m.group(1) + "]", m.end())
            if end < 0:
                raise ToolError("unterminated long comment")
            return end + len(m.group(1)) + 2
        nl = text.find("\n", i)
        return len(text) if nl < 0 else nl
    if c in "\"'`":
        j = i + 1
        while j < len(text):
            ch = text[j]
            if ch == "\\":
                j += 2
                continue
            if ch == c:
                return j + 1
            if ch == "\n" and c != "`":
                raise ToolError(f"unterminated string at offset {i}")
            j += 1
        raise ToolError(f"unterminated string at offset {i}")
    if c == "[":
        m = _LONG_OPEN.match(text, i)
        if m:
            end = text.find("]" + m.group(1) + "]", m.end())
            if end < 0:
                raise ToolError("unterminated long string")
            return end + len(m.group(1)) + 2
    return None


class Node:
    __slots__ = ("key", "key_start", "open", "close", "children", "parent")

    def __init__(self, key: str | None, key_start: int, open_: int, parent: "Node | None") -> None:
        self.key, self.key_start, self.open, self.close = key, key_start, open_, -1
        self.children: list[Node] = []
        self.parent = parent


def _key_before(text: str, i: int) -> tuple[str | None, int]:
    j = i - 1
    while j >= 0 and text[j] in " \t\r\n":
        j -= 1
    if j < 0 or text[j] != "=" or (j > 0 and text[j - 1] in "=~<>"):
        return None, i
    j -= 1
    while j >= 0 and text[j] in " \t\r\n":
        j -= 1
    end = j + 1
    while j >= 0 and (text[j].isalnum() or text[j] == "_"):
        j -= 1
    name = text[j + 1:end]
    if not name or name[0].isdigit():
        return None, i
    return name, j + 1


def parse_tables(text: str) -> Node:
    root = Node(None, 0, -1, None)
    root.close = len(text)
    stack = [root]
    i, n = 0, len(text)
    while i < n:
        j = _skip(text, i)
        if j is not None:
            i = j
            continue
        c = text[i]
        if c == "{":
            k, ks = _key_before(text, i)
            node = Node(k, ks, i, stack[-1])
            stack[-1].children.append(node)
            stack.append(node)
        elif c == "}":
            if len(stack) == 1:
                raise ToolError(f"unbalanced '}}' at offset {i}")
            stack.pop().close = i
        i += 1
    if len(stack) != 1:
        raise ToolError("unbalanced '{' (file does not parse)")
    return root


