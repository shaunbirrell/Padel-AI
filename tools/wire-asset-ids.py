def parse_got(text: str) -> set[int]:
    out: set[int] = set()
    for line in text.splitlines():
        s = line.strip()
        if not s or s.upper().startswith("SKIP"):
            continue
        if s.upper().startswith("GOT"):
            out.update(int(x) for x in re.findall(r"\d{5,}", s))
        elif re.fullmatch(r"[\d,\s]+", s):
            out.update(int(x) for x in re.findall(r"\d{5,}", s))
    return out


def parse_we_check(text: str) -> dict[int, dict]:
    out: dict[int, dict] = {}
    for line in text.splitlines():
        m = re.search(r"WE_CHECK (OK|FAIL) (\d+)\b(.*)$", line)
        if not m:
            continue
        aid = int(m.group(2))
        if m.group(1) == "FAIL":
            out[aid] = {"ok": False, "why": m.group(3).strip()[:120]}
            continue
        if out.get(aid, {}).get("ok") is False:
            continue
        # the counts follow `kids=[...]` (the model's child names, which could contain "parts=1"): read after it and
        # take the last match of each field
        rest = m.group(3)
        rest = rest[rest.rfind("] ") + 1:] if "kids=[" in rest and "] " in rest else rest
        rec: dict = {"ok": True}
        for k in ("parts", "humanoids", "scripts", "lights", "decals"):
            mm = re.findall(rf"(?<![\w=]){k}=(\d+)", rest)
            rec[k] = int(mm[-1]) if mm else None
        mm = re.findall(r"(?<![\w=])size=([\d.]+)x([\d.]+)x([\d.]+)", rest)
        rec["size"] = tuple(float(x) for x in mm[-1]) if mm else None
        out[aid] = rec
    return out


