# ── file set with dry-run / restore ───────────────────────────────────────────────────────────────────────────────
class Files:
    def __init__(self, root: Path) -> None:
        self.root = root
        self.orig: dict[str, str | None] = {}
        self.cur: dict[str, str | None] = {}

    def get(self, rel: str) -> str | None:
        if rel not in self.cur:
            t = read_text(self.root, rel)
            self.orig[rel] = t
            self.cur[rel] = t
        return self.cur[rel]

    def set(self, rel: str, text: str | None) -> None:
        self.get(rel)
        self.cur[rel] = text

    def changed(self) -> list[str]:
        return [r for r in self.cur if self.cur[r] != self.orig[r]]

    def diff(self, skip: tuple[str, ...] = (JOURNAL_REL,)) -> str:
        out = []
        for rel in self.changed():
            if rel in skip:
                out.append(f"(diff of {rel} not shown: the undo journal)\n")
                continue
            a = (self.orig[rel] or "").splitlines(keepends=True)
            b = (self.cur[rel] or "").splitlines(keepends=True)
            out.extend(difflib.unified_diff(a, b, f"a/{rel}", f"b/{rel}"))
        return "".join(out)

    def write(self) -> None:
        for rel in self.changed():
            p = self.root / rel
            if self.cur[rel] is None:
                if p.exists():
                    p.unlink()
            else:
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_text(self.cur[rel], encoding="utf-8")  # type: ignore[arg-type]

    def restore(self) -> None:
        for rel in self.changed():
            p = self.root / rel
            if self.orig[rel] is None:
                if p.exists():
                    p.unlink()
            else:
                p.write_text(self.orig[rel], encoding="utf-8")  # type: ignore[arg-type]


# ── verify (luau-compile + BuyPathStatic, no new FAIL) ───────────────────────────────────────────────────────────
def run_bps(root: Path) -> tuple[int | None, list[str], str]:
    env = dict(os.environ)
    exe = env.get("LUAU_COMPILE") or shutil.which("luau-compile")
    if exe:
        env["LUAU_COMPILE"] = exe
    r = subprocess.run([sys.executable, str(root / BPS_REL)], cwd=root, env=env, capture_output=True, text=True)
    m = re.search(r"Done PASS=(\d+) FAIL=(\d+)", r.stdout)
    fails = [ln for ln in (r.stdout + r.stderr).splitlines() if "[BuyPathStatic] FAIL" in ln]
    return (int(m.group(2)) if m else None), fails, (m.group(0) if m else "BuyPathStatic did not finish")


def compile_luau(root: Path, rels: list[str]) -> str | None:
    exe = os.environ.get("LUAU_COMPILE") or shutil.which("luau-compile")
    if not exe:
        return "luau-compile not found: set LUAU_COMPILE=/path/luau-compile (or pass --no-verify for a scratch run)"
    for rel in rels:
        r = subprocess.run([exe, "--binary", str(root / rel)], stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, text=True)
        if r.returncode != 0:
            return f"luau-compile {rel}: {(r.stderr or '').strip().splitlines()[:1]}"
    return None


# ── commands ──────────────────────────────────────────────────────────────────────────────────────────────────────
def resolve_ids(args_in: list[str], batch: str | None) -> tuple[list[int], list[str]]:
    ids: list[int] = []
    refused: list[str] = []
    if batch:
        if batch not in BATCHES:
            raise ToolError(f"unknown batch {batch} (P1, P1i, P2, P3)")
        ids.extend(BATCHES[batch])
    for a in args_in:
        if a.isdigit():
            aid = int(a)
            if aid in PENDING_BY_ID:
                ids.append(aid)
                continue
            known = [r for r in REG.values() if r.id == aid or r.owner_id == aid]
            if known:
                refused.append(f"REFUSED {aid}: {known[0].key} is {known[0].decision} ({known[0].why})")
            else:
                refused.append(f"REFUSED {aid}: unknown id (not on the owner's verified list)")
            continue
        r = REG.get(a)
        if not r:
            refused.append(f"REFUSED {a}: unknown key (not on the owner's list)")
        elif r.decision != "PENDING-GET":
            refused.append(f"REFUSED {a}: {r.decision} — {r.why}")
        else:
            ids.append(r.id)
    seen: list[int] = []
    for i in ids:
        if i not in seen:
            seen.append(i)
    return seen, refused


def load_journal(files: Files) -> dict:
    t = files.get(JOURNAL_REL)
    if t is None:
        return {"version": 1, "about": "undo journal of tools/wire-asset-ids.py (demote); edit only through the tool",
                "created_by_tool": True, "promoted": {}}
    try:
        j = json.loads(t)
    except ValueError as e:
        raise ToolError(f"{JOURNAL_REL} is not valid JSON ({e}); restore it from git before promoting or demoting")
    if not isinstance(j, dict) or not isinstance(j.get("promoted"), dict):
        raise ToolError(f"{JOURNAL_REL} has no 'promoted' table; restore it from git")
    return j


def save_journal(files: Files, j: dict) -> None:
    if not j["promoted"] and j.get("created_by_tool"):
        files.set(JOURNAL_REL, None)
    else:
        files.set(JOURNAL_REL, json.dumps(j, indent=1, sort_keys=True, ensure_ascii=False) + "\n")


