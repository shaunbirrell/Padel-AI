class Pin:
    __slots__ = ("line", "kind", "path", "needle", "label", "src")

    def __init__(self, line: int, kind: str, path: str, needle: str, label: str, src: str) -> None:
        self.line, self.kind, self.path, self.needle, self.label, self.src = line, kind, path, needle, label, src


def parse_pins(bps: str) -> list[Pin]:
    """Single-line must_contain / must_not_contain calls whose path is a literal or a module-level string constant
    (`AW_VAC = "src/..."`) and whose needle and label are literals. Anything else is left to the verify run."""
    consts = dict(re.findall(r"""^([A-Z_][A-Z0-9_]*)\s*=\s*["']([^"'\n]+)["']\s*$""", bps, re.M))
    pins = []
    for idx, line in enumerate(bps.split("\n")):
        s = line.strip()
        if not (s.startswith("must_contain(") or s.startswith("must_not_contain(")):
            continue
        try:
            call = ast.parse(s).body[0].value  # type: ignore[attr-defined]
            nodes = call.args
            path = nodes[0].value if isinstance(nodes[0], ast.Constant) else consts.get(getattr(nodes[0], "id", ""))
            needle, label = nodes[1].value, nodes[2].value
        except (SyntaxError, AttributeError, IndexError):
            continue
        if len(nodes) == 3 and all(isinstance(a, str) for a in (path, needle, label)):
            pins.append(Pin(idx, call.func.id, path, needle, label, line))
    return pins


def _replace_literal(line: str, value_old: str, value_new: str, arg_index: int) -> str:
    indent = len(line) - len(line.lstrip())
    body = line.strip()
    try:
        call = ast.parse(body).body[0].value  # type: ignore[attr-defined]
        node = call.args[arg_index]
        # ast offsets are UTF-8 byte offsets; labels such as "v42 MissileDefense ≠ Watchtower" hold non-ASCII text
        raw = body.encode("utf-8")
        s = indent + len(raw[:node.col_offset].decode("utf-8"))
        e = indent + len(raw[:node.end_col_offset].decode("utf-8"))
        lit = line[s:e]
        ok = lit[:1] in ("\"", "'") and ast.literal_eval(lit) == value_old
    except (SyntaxError, ValueError, AttributeError, IndexError, UnicodeDecodeError):
        ok = False
    if not ok:
        raise ToolError(f"BuyPathStatic line not in the simple form: {body[:80]}")
    q = lit[0]
    esc = (value_new.replace("\\", "\\\\").replace(q, "\\" + q).replace("\n", "\\n").replace("\t", "\\t")
           .replace("\r", "\\r"))
    return line[:s] + q + esc + q + line[e:]


def rewrite_pins(bps: str, rel: str, old_text: str, new_text: str, swaps: list[tuple[int, int]], suffix: str) -> tuple[str, list[str]]:
    """Rewrite must_contain needles on `rel` that this edit breaks (old id -> new id). Refuses what it cannot fix."""
    lines = bps.split("\n")
    notes: list[str] = []
    for p in parse_pins(bps):
        if p.path != rel:
            continue
        before, after = p.needle in old_text, p.needle in new_text
        if p.kind == "must_not_contain":
            if not before and after:
                raise ToolError(f"BuyPathStatic line {p.line + 1} forbids `{p.needle}` in {rel}")
            continue
        if not before or after:
            continue
        cand = None
        for old_id, new_id in swaps:
            tries = []
            if f"ModelAssetId = {old_id}" in p.needle:
                tries.append(p.needle.replace(f"ModelAssetId = {old_id}", f"ModelAssetId = {new_id}"))
            if old_id and id_token(old_id).search(p.needle):
                tries.append(id_token(old_id).sub(str(new_id), p.needle))
            cand = next((t for t in tries if t in new_text), None)
            if cand:
                break
        if not cand:
            raise ToolError(f"BuyPathStatic line {p.line + 1} (`{p.needle}`, {p.label}) breaks and has no old->new id form")
        line = _replace_literal(lines[p.line], p.needle, cand, 1)
        if suffix and suffix not in p.label:
            line = _replace_literal(line, p.label, p.label + suffix, 2)
        lines[p.line] = line
        notes.append(f"BuyPathStatic line {p.line + 1}: `{p.needle}` -> `{cand}`")
    return "\n".join(lines), notes


# ── licence rows ─────────────────────────────────────────────────────────────────────────────────────────────────
def _row_prefix(asset_id: int) -> str:
    return f"| [{asset_id}](https://create.roblox.com/store/asset/{asset_id}) |"


def licence_row(asset_id: int, rows: list[Row], used_by: list[str], verified: str, notes: str) -> str:
    s = STORE[asset_id]
    tris = f"{s[6]:,}" if isinstance(s[6], int) else "—"
    scripts = f"{s[7]} (stripped)" if isinstance(s[7], int) else "—"
    kind = {10: "Model", 4: "Mesh", 1: "Image"}.get(s[4], str(s[4]))
    used = ", ".join(f"`{u}`" for u in used_by)
    return f"{_row_prefix(asset_id)} {s[0]} | {s[1]} ({s[3]} {s[2]}) | {kind} | {verified} | {tris} | {scripts} | {used} | {notes} |"


def add_licence_row(lic: str, row: str, asset_id: int) -> tuple[str, bool]:
    """Append the id's row to the '3.1 Owner picks' table once (a second run adds nothing)."""
    heads = list(re.finditer(r"\n#{2,3} 3\.1 ", lic))
    if LIC_PICKS_END not in lic or not heads:
        raise ToolError(f"{LIC_REL}: section '3.1 Owner picks' or marker {LIC_PICKS_END} missing")
    head, tail = lic.split(LIC_PICKS_END, 1)
    if _row_prefix(asset_id) in head[heads[-1].start():]:
        return lic, False
    if not head.endswith("\n"):
        head += "\n"
    return head + row + "\n" + LIC_PICKS_END + tail, True


def _section3_bounds(lic: str) -> tuple[int, int]:
    s = lic.find("\n## 3. ")
    if s < 0:
        return -1, -1
    e = lic.find("\n## 4.", s)
    return s, (len(lic) if e < 0 else e)


def move_replaced_row(lic: str, old_id: int, note: str) -> tuple[str, dict | None]:
    """Move the §3 row of an id that left src/ to the 'Replaced by owner picks' table. Returns the move record."""
    s, e = _section3_bounds(lic)
    if s < 0 or LIC_REPLACED_END not in lic:
        return lic, None
    prefix = _row_prefix(old_id)
    idx = lic.find("\n" + prefix, s, e)
    if idx < 0:
        return lic, None
    ls = idx + 1
    le = lic.find("\n", ls)
    row = lic[ls:le]
    heading_at = lic.rfind("\n### ", 0, ls)
    heading = lic[heading_at + 1:lic.find("\n", heading_at + 1)] if heading_at >= 0 else ""
    table_start = heading_at if heading_at >= 0 else s
    before_ids = [int(x) for x in re.findall(r"^\| \[(\d+)\]\(", lic[table_start:ls], re.M)]
    lic = lic[:ls] + lic[le + 1:]
    moved = _append_note(row, note)
    head, tail = lic.split(LIC_REPLACED_END, 1)
    if not head.endswith("\n"):
        head += "\n"
    lic = head + moved + "\n" + LIC_REPLACED_END + tail
    return lic, {"row": row, "heading": heading, "before_ids": before_ids}


def _append_note(row: str, note: str) -> str:
    """Append to the last cell of a markdown table row."""
    body = row.rstrip()
    if not body.endswith("|"):
        return f"{body} {note}"
    cut = body[:-1].rstrip().rfind(" |")
    if cut < 0:
        return f"{body[:-1].rstrip()} {note} |"
    cell = body[cut + 2:-1].strip()
    return f"{body[:cut + 2]} {cell + '; ' if cell else ''}{note} |"


def note_kept_row(lic: str, old_id: int, note: str) -> str:
    """An old id that stays in src/ (another field still uses it): note the moved fields on its §3 row."""
    s, e = _section3_bounds(lic)
    if s < 0:
        return lic
    idx = lic.find("\n" + _row_prefix(old_id), s, e)
    if idx < 0:
        return lic
    le = lic.find("\n", idx + 1)
    return lic[:idx + 1] + _append_note(lic[idx + 1:le], note) + lic[le:]


def unmove_row(lic: str, mv: dict) -> str:
    heading = mv["heading"]
    hs = lic.find("\n" + heading + "\n") if heading else -1
    if hs < 0:
        raise ToolError(f"cannot restore licence row: heading {heading!r} not found")
    start = hs + 1 + len(heading) + 1
    nxt = lic.find("\n#", start)
    end = len(lic) if nxt < 0 else nxt
    lines = lic[start:end].split("\n")
    insert_at = None
    for i, line in enumerate(lines):
        m = re.match(r"^\| \[(\d+)\]\(", line)
        if m and int(m.group(1)) in mv["before_ids"]:
            insert_at = i + 1
        if line.startswith("|---"):
            insert_at = insert_at if insert_at is not None else i + 1
    if insert_at is None:
        raise ToolError("cannot restore licence row: table not found")
    lines.insert(insert_at, mv["row"])
    return lic[:start] + "\n".join(lines) + lic[end:]


# ── journal hunks (demote) ────────────────────────────────────────────────────────────────────────────────────────
def make_hunks(old: str, new: str) -> list[list[str]]:
    a, b = old.splitlines(keepends=True), new.splitlines(keepends=True)
    ops = [o for o in difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes() if o[0] != "equal"]
    spans = []
    for _tag, i1, i2, j1, j2 in ops:
        for c in range(0, 25):
            ii1, ii2, jj1, jj2 = max(0, i1 - c), min(len(a), i2 + c), max(0, j1 - c), min(len(b), j2 + c)
            after = "".join(b[jj1:jj2])
            if after and new.count(after) == 1:
                spans.append([ii1, ii2, jj1, jj2])
                break
        else:
            raise ToolError("cannot record an undo hunk (text not unique)")
    merged: list[list[int]] = []
    for sp in sorted(spans, key=lambda x: x[2]):
        if merged and sp[2] <= merged[-1][3]:
            merged[-1] = [min(merged[-1][0], sp[0]), max(merged[-1][1], sp[1]), merged[-1][2], max(merged[-1][3], sp[3])]
        else:
            merged.append(sp)
    return [["".join(a[i1:i2]), "".join(b[j1:j2])] for i1, i2, j1, j2 in merged]


def revert_hunks(text: str, hunks: list[list[str]], rel: str) -> str:
    for before, after in hunks:
        n = text.count(after)
        if n != 1:
            raise ToolError(f"{rel}: the promoted text changed since (found {n}x); demote by hand")
        text = text.replace(after, before, 1)
    return text


